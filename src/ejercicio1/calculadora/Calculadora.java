    /**
     * Metodo para quita el .0 en caso de que el resultado sea entero.
     *
     * @param resultado
     * @return
     */
    private String quitarCero(float resultado) {
        String retorno = "";
        retorno = Float.toString(resultado);

        if (resultado % 1 == 0) { //si resto es 0
            return retorno.substring(0, retorno.length() - 2);//quito 2 caracteres
        } else {
            return retorno;
        }

    }

