    private void igualActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_igualActionPerformed

        if (this.resultado.getText() == "") {//impedimos que salte la excepcion al intentar poner un = al principio

        } else {

            this.operando2 = Float.parseFloat(this.resultado.getText());//asignamos valor de resultado al operando 2

            //en funcion del operador
            switch (this.operador) {

                case "+":
                    this.resultado.setText(quitarCero(this.operando1 + this.operando2));//sumo los 2 operandos y los convierto a String asignandolo a resultao

                    break;
                case "-":
                    this.resultado.setText(quitarCero(this.operando1 - this.operando2));//resto los 2 operandos y los convierto a String asignandolo a resultao

                    break;
                case "*":
                    this.resultado.setText(quitarCero(this.operando1 * this.operando2));//multiplico los 2 operandos y los convierto a String asignandolo a resultao

                    break;
                case "/":// controlo que no se pueda dividir por 0
                    
                    if (this.operando2 == 0) {
                        this.resultado.setText("No podemos / por cero  ");
                    } else {
                        this.resultado.setText(quitarCero(this.operando1 / this.operando2));//divido los 2 operandos y los convierto a String asignandolo a resultao
                    }

                    break;

            }

        }


    }//GEN-LAST:event_igualActionPerformed

